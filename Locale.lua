FW.LOCALES = LOCALES
FW.activeLocale = "enUS"

local function ResolveLocaleCode(pref)
    if pref and pref ~= "AUTO" and LOCALES[pref] then
        return pref
    end
    local client = GetLocale and GetLocale() or "enUS"
    if LOCALES[client] then
        return client
    end
    return "enUS"
end

FW.L = setmetatable({}, {
    __index = function(_, key)
        local active = LOCALES[FW.activeLocale]
        if active and active[key] ~= nil then
            return active[key]
        end
        if LOCALES.enUS[key] ~= nil then
            return LOCALES.enUS[key]
        end
        return tostring(key)
    end,
})

function FW.ApplyLocale(pref)
    FW.activeLocale = ResolveLocaleCode(pref)
    if FW.RefreshLocalizedTables then
        FW.RefreshLocalizedTables()
    end
end

